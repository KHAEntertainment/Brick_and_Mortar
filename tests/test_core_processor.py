def test_prusa_processing():
    """Test PrusaSlicer output: ";LAYER_CHANGE" markers (no colon) and Z-lift around layer changes"""
    print("\nTesting PrusaSlicer G-code...")
    
    def prusa_layer(z, lift):
        # Structure follows PrusaSlicer 2.x output with retract_lift enabled
        return [
            ";LAYER_CHANGE",
            f";Z:{z}",
            ";HEIGHT:0.2",
            ";BEFORE_LAYER_CHANGE",
            f";{z}",
            f"G1 Z{lift} F720",
            ";AFTER_LAYER_CHANGE",
            f";{z}",
            "G1 X10 Y10 F9000",
            f"G1 Z{z} F720",
            "G1 E.8 F2100",
            ";TYPE:External perimeter",
            ";WIDTH:0.45",
            "G1 F1200",
            "G1 X20 Y10 E.5",
            "G1 X20 Y20 E.5",
            "G1 E-.8 F2100",
            f"G1 Z{lift} F720",
            "G1 X30 Y30 F9000",
            f"G1 Z{z} F720",
            "G1 E.8 F2100",
            ";TYPE:Solid infill",
            "G1 X40 Y30 E.5 F1500",
            "G1 E-.8 F2100",
            f"G1 Z{lift} F720",
        ]
    
    sample_gcode = [
        "; generated by PrusaSlicer 2.7.4+win64 on 2025-07-10 at 12:00:00 UTC",
        "M83 ; use relative distances for extrusion",
        "G28 ; home all axes",
    ]
    for z, lift in ((0.2, 0.6), (0.4, 0.8), (0.6, 1.0)):
        sample_gcode += prusa_layer(z, lift)
    
    processor = GCodeProcessor()
    info = processor.get_file_info(sample_gcode)
    assert info["slicer_format"] == "prusa", f"Expected prusa, got {info['slicer_format']}"
    assert info["estimated_layers"] == 3, f"Expected 3 layers, got {info['estimated_layers']}"
    assert info["estimated_layer_height"] == 0.2, f"Expected 0.2mm, got {info['estimated_layer_height']}"
    
    is_valid, errors = processor.validate_gcode(sample_gcode)
    assert is_valid, f"Prusa G-code rejected: {errors}"
    
    params = ProcessingParams.from_preset("PETG_TPU")
    params.enable_preview = False
    response = processor.process(sample_gcode, params)
    assert response.success, f"Processing failed: {response.error}"
    assert response.processing_stats.mortar_layers_added == 2, \
        f"Expected 2 mortar layers, got {response.processing_stats.mortar_layers_added}"
    
    # Mortar sits z_offset above the layer it copies, not above the Z-lift
    output = response.processed_gcode
    header_zs = [float(line.split("Z=")[1]) for line in output if line.startswith(";BRICK_MORTAR_LAYER ")]
    assert header_zs == [0.3, 0.5], f"Expected mortar at Z 0.3 and 0.5, got {header_zs}"
    
    # No slicer tool-change sequence in Prusa output: bare tool change, then wait for temperature
    gcode_text = "\n".join(output)
    assert "T1 ;TOOL_CHANGE" in gcode_text
    assert f"M109 S{params.mortar_temp}" in gcode_text
    assert "T0 ;TOOL_CHANGE" in gcode_text
    
    print("   ✅ PrusaSlicer layer changes detected (3 layers, 0.2mm)")
    print(f"   ✅ Mortar layers at Z {header_zs}")

def test_orca_h2d_tool_change():
    """Test OrcaSlicer 2.5 H2D tool changes, which write "M620 S1A H-1" / "T1 H-1" """
    print("\nTesting OrcaSlicer 2.5 H2D tool changes...")
    
    def layer(n, z):
        return [
            "; CHANGE_LAYER",
            f"; Z_HEIGHT: {z}",
            f"M991 S0 P{n} ;notify layer change",
            "G1 X10 Y10 F30000",
            f"G1 Z{z}",
            "G1 E.8 F1800",
            "G1 X20 Y10 E.5 F1200",
            "G1 X20 Y20 E.5",
            "G1 E-.8 F1800",
        ]
    
    def swap(tool, z):
        # Shape of OrcaSlicer 2.5's expanded H2D change_filament_gcode, trimmed
        return [
            "; CP TOOLCHANGE START",
            "; filament end gcode ",
            ";======== H2D ========",
            f"M620 S{tool}A H-1",
            "M1002 gcode_claim_action : 4",
            f"G1 Z{z + 3:.1f} F1200",
            f"T{tool} H-1",
            "M83",
            f"G1 Z{z + 3:.1f} F3000",
            f"M621 S{tool}A H-1",
            "M1002 gcode_claim_action : 0",
            "; CP TOOLCHANGE END",
            f"G1 Z{z}",
        ]
    
    sample_gcode = [
        "; HEADER_BLOCK_START",
        "; generated by OrcaSlicer 2.5.0-beta on 2026-10-28 at 18:26:29",
        "; HEADER_BLOCK_END",
        "; CONFIG_BLOCK_START",
        "; filament_map = 2,1",
        "; nozzle_temperature = 220,230",
        "; physical_extruder_map = 1,0",
        "; CONFIG_BLOCK_END",
        "M83",
    ]
    # Layer 1 prints a small TPU tab, so Orca writes both swap sequences
    sample_gcode += layer(0, 0.2)
    sample_gcode += swap(1, 0.2)
    sample_gcode += ["G1 X30 Y30 F30000", "G1 E.8 F1800", "G1 X40 Y30 E.5 F1200", "G1 E-.8 F1800"]
    sample_gcode += swap(0, 0.2)
    sample_gcode += layer(1, 0.4)
    sample_gcode += layer(2, 0.6)
    
    # Parser: trailing arguments accepted, utility tools still ignored
    assert GCodeParser.get_tool_change("T1 H-1") == "T1"
    assert GCodeParser.get_tool_change("T0") == "T0"
    assert GCodeParser.get_tool_change("T1000") is None
    assert GCodeParser.get_tool_change("T65535") is None
    
    # Library: both sequences found; filament_map 2,1 + physical_extruder_map 1,0 puts TPU on nozzle 1
    library = ToolChangeLibrary.from_gcode(sample_gcode, SlicerFormat.ORCA)
    assert library.has("T0") and library.has("T1"), f"Sequences found: {sorted(library.templates)}"
    assert library.heater_index("T1") == 1, f"TPU heater: {library.heater_index('T1')}"
    assert library.heater_index("T0") == 0, f"PLA heater: {library.heater_index('T0')}"
    assert any(line == "T1 H-1" for line in library.templates["T1"][0])
    
    params = ProcessingParams.from_preset("PETG_TPU")
    params.enable_preview = False
    response = GCodeProcessor().process(sample_gcode, params)
    assert response.success, f"Processing failed: {response.error}"
    assert response.processing_stats.mortar_layers_added == 2
    
    gcode_text = "\n".join(response.processed_gcode)
    assert "no slicer tool-change sequence" not in gcode_text, "Fell back to a bare tool change"
    assert gcode_text.count(";TOOL_CHANGE_START T1") == 2
    assert gcode_text.count(";TOOL_CHANGE_START T0") == 2
    # nozzle_temperature = 220,230: the TPU filament (T1) prints at 230
    assert "M104 T1 S230 ; preheat mortar nozzle" in gcode_text
    assert "M109 S230 ; wait for mortar nozzle temperature" in gcode_text
    # Swap lift re-based from layer 0.2 (Z3.2) to the first mortar layer at 0.3
    assert "G1 Z3.300 F1200" in gcode_text
    # The slicer's own swap moves are not copied into mortar layers
    mortar_1 = gcode_text.split(";BRICK_MORTAR_LAYER 1 ")[1].split(";TOOL_CHANGE_START T0")[0]
    mortar_moves = mortar_1.split(";TOOL_CHANGE_END T1")[1]
    assert "Z3." not in mortar_moves, "Swap lift copied into mortar"
    # Only base-tool (PETG) moves become mortar: the TPU tab gets no mortar copy
    assert "G1 X20.200 Y10.200" in mortar_moves, "Base-tool moves missing from mortar"
    assert "G1 X30.200 Y30.200" not in mortar_moves, "TPU tab copied into mortar"
    assert "G1 X40.200 Y30.200" not in mortar_moves, "TPU tab copied into mortar"
    
    print("   ✅ \"M620 S1A H-1\" / \"T1 H-1\" sequences found for T0 and T1")
    print("   ✅ Mortar uses the slicer sequences and preheats nozzle 1 (TPU) to 230°C")
    print("   ✅ TPU tab moves are not copied into mortar layers")

def test_mortar_temperature_source():
    """Test where the mortar temperature comes from: slicer file, explicit override, fallback"""
    print("\nTesting mortar temperature source...")
    
    def sample(config_lines):
        lines = ["; generated by OrcaSlicer 2.5.2"] + config_lines + ["M83"]
        for n, z in enumerate((0.2, 0.4)):
            lines += [
                f"M991 S0 P{n} ;notify layer change",
                f"G1 Z{z}",
                "G1 X10 Y10 F30000",
                "G1 X20 Y10 E.5 F1200",
            ]
        return lines
    
    with_temps = sample(["; nozzle_temperature = 250,228"])
    processor = GCodeProcessor()
    
    # Default: the mortar filament's (T1) temperature from the slicer file
    params = ProcessingParams(enable_preview=False)
    response = processor.process(with_temps, params)
    assert response.success, response.error
    assert response.processing_stats.mortar_temp == 228
    assert response.processing_stats.mortar_temp_source == "slicer"
    assert "M109 S228 ;" in "\n".join(response.processed_gcode)
    
    # Explicit temperature wins over the file
    params = ProcessingParams(enable_preview=False, mortar_temp=240, use_slicer_temp=False)
    response = processor.process(with_temps, params)
    assert response.processing_stats.mortar_temp == 240
    assert response.processing_stats.mortar_temp_source == "params"
    assert "M109 S240 ;" in "\n".join(response.processed_gcode)
    assert "M109 S228 ;" not in "\n".join(response.processed_gcode)
    
    # No temperature in the file: fall back to params.mortar_temp
    params = ProcessingParams(enable_preview=False)
    response = processor.process(sample([]), params)
    assert response.processing_stats.mortar_temp == params.mortar_temp
    assert response.processing_stats.mortar_temp_source == "params"
    
    print("   ✅ Uses the slicer's T1 temperature (228°C) by default")
    print("   ✅ Explicit mortar_temp overrides it; falls back without a slicer value")

